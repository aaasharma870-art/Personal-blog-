// Builds the served prologue controller:
//   components/intro/controller.js (readable source, edit this)
//     → public/intro/intro.js     (minified; SPEC v2 §5.1 "a tiny vanilla
//                                   module"; loaded by the head script)
//     → components/intro/controller-version.ts (the served file's content
//                                   hash: the ?v= cache-buster, never bumped
//                                   by hand)
// Run:  node components/intro/build-controller.mjs
// Uses the terser that ships inside Next (no new dependency). The banner
// records the source's sha1, so a stale served file is visible in review.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { minify } = require("next/dist/compiled/terser");

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const srcPath = join(here, "controller.js");
const outPath = join(root, "public", "intro", "intro.js");
const versionPath = join(here, "controller-version.ts");

const src = readFileSync(srcPath, "utf8");
const srcHash = createHash("sha1").update(src).digest("hex").slice(0, 12);
const { code } = await minify(src, {
  ecma: 2019,
  compress: { passes: 2 },
  mangle: true,
  format: { comments: false },
});
const banner = `/* eslint-disable */\n/* Prologue controller (SPEC v2 §5). GENERATED from components/intro/controller.js by components/intro/build-controller.mjs, do not edit. src:${srcHash} */\n`;
const out = banner + code + "\n";
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
const version = createHash("sha1").update(out).digest("hex").slice(0, 10);
writeFileSync(
  versionPath,
  [
    "// GENERATED by components/intro/build-controller.mjs, do not edit.",
    `/** Content hash of public/intro/intro.js (built from controller.js src:${srcHash}). */`,
    `export const INTRO_CONTROLLER_VERSION = "${version}";`,
    "",
  ].join("\n"),
);
console.log(
  `public/intro/intro.js: ${out.length} B, ${gzipSync(out, { level: 9 }).length} B gz (source ${src.length} B, src:${srcHash})`,
);
